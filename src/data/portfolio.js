const LEGACY_MAP = {
  obsidian: "wine",
  emerald: "cashmere",
  cobalt: "sapphire",
};

export function getActiveTheme(themeKey = "wine", mode = "dark") {
  const resolvedKey = THEMES[themeKey] ? themeKey : (LEGACY_MAP[themeKey] || "wine");
  const base = THEMES[resolvedKey] || THEMES.wine;
  const currentMode = mode === "light" ? "light" : "dark";
  const config = base[currentMode] || base.dark;
  return {
    id: base.id,
    name: base.name,
    pillColor: base.pillColor,
    accent: base.accent,
    mode: currentMode,
    ...config,
  };
}

